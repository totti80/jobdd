    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">1. 2D CADと3D CADをどう使っていたか</h2>
        <p class="mt-3">2D CADでは図面上の寸法や形状を、3D CADでは立体の形状や部品の組み合わせを扱います。ただし、使うソフトだけで仕事の難しさや担当範囲が決まるわけではありません。</p>
        <p class="mt-3">「組立図と部品図を作成した」「モデルを使って干渉を確認した」など、実際に行った作業を添えると、自分の経験を具体的に説明できます。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">2. ソフト名と使用の頻度を整理する</h2>
        <p class="mt-3">AutoCAD、Inventor、SolidWorksなど、使ったソフト名を書き出し、いつ、どのくらい使っていたかを整理しましょう。学習で触れた経験と、日常業務で使った経験は分けて記載すると伝わりやすくなります。</p>
        <p class="mt-3">同じソフトでも、図面の修正が中心だったのか、形状の検討から担当したのかで経験は異なります。ソフトの優劣ではなく、自分が何に使っていたかを見ることが大切です。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">3. どの設計工程で使っていたか</h2>
        <p class="mt-3">構想、基本設計、詳細設計、製作図作成、評価、不具合対応など、関わった工程を挙げてみてください。「詳細設計の部品図作成」と「構想段階の配置検討」では、考える内容や関係者への確認事項が異なります。</p>
        <p class="mt-3">複数の工程に関わっていた場合は、中心となる工程と補助的に担当した工程を分けると、求人の担当工程と照らし合わせやすくなります。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">4. 何を設計したかを具体化する</h2>
        <p class="mt-3">生産設備、搬送装置、配管周辺の支持部品など、設計した対象を、公開できる範囲で整理します。製品名を出せなくても、用途、部品の種類、設備全体のどの部分を担当したかは説明できる場合があります。</p>
        <p class="mt-3">守秘義務に触れる図面や顧客情報を使う必要はありません。「既存設備の部品変更」「装置の架台設計」といった表現でも、経験の輪郭を伝えられます。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">5. 自分の判断と、相談した範囲を分ける</h2>
        <p class="mt-3">寸法の変更、材料の選定、配置の検討など、自分で提案・判断したことと、指示を受けて作業したことを分けましょう。上司のレビューや製造担当との相談も、仕事の進め方を説明する材料になります。</p>
        <p class="mt-3">例えば「既存図面の変更を担当し、組立時の干渉を製造担当と確認。変更案は上司のレビュー後に確定」と書くと、作業内容と責任の範囲が見えます。担当範囲を大きく見せる必要はありません。</p>
    </section>
    <section class="jobdd-decision-note">
        <h2 class="text-xl font-bold leading-8 text-blue-950">自分の場合を整理して、比べる</h2>
        <p class="mt-3">ソフト名・工程・設計対象・担当範囲を一組にして、自分の経験を整理してみてください。求人側で分からない項目は未確認のまま残し、面談で確かめる質問にできます。こうした観点で求人を比較すると、経験を生かしたい部分と、これから学びたい部分を考えやすくなります。</p>
    </section>
