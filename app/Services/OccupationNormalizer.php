        |--------------------------------------------------------------------------
        | 施工管理
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $description,
            [
                '募集職種 施工管理',
                '施工管理業務',
                '施工管理を担当',
            ]
        )) {
            return '施工管理';
        }

        /*
        |--------------------------------------------------------------------------
        | プラントエンジニア
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $description,
            [
                '募集職種 プラントエンジニア',
                '募集職種 プロセスエンジニア',
                'プラントエンジニアリング業務',
            ]
        )) {
            return 'プラントエンジニア';
        }

        return null;
    }


    /**
     * 文字列正規化
     */
    private function normalizeText(
        ?string $text
    ): string {
        if ($text === null) {
            return '';
        }

        $text = trim($text);

        if ($text === '') {
            return '';
        }

        /*
         * 英字の大文字小文字差をなくす。
         */
        $text = mb_strtolower(
            $text,
            'UTF-8'
        );

        /*
         * 全角スペースを半角へ。
         */
        $text = str_replace(
            '　',
            ' ',
            $text
        );

        /*
         * 改行・タブ等をスペースへ。
         */
        $text = preg_replace(
            '/\s+/u',
            ' ',
            $text
        ) ?? $text;

        return trim($text);
    }


    /**
     * キーワードのいずれかを含むか
     */
    private function containsAny(
        string $text,
        array $keywords
    ): bool {
        foreach ($keywords as $keyword) {

            $keyword = mb_strtolower(
                $keyword,
                'UTF-8'
            );

            if (str_contains(
                $text,
                $keyword
            )) {
                return true;
            }
        }

        return false;
    }
}
