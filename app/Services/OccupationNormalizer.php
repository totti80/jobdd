<?php

namespace App\Services;

class OccupationNormalizer
{
    /**
     * 求人タイトル・仕事内容からJobDD共通職種へ正規化する。
     *
     * 方針:
     * - 検索キーワードは職種FACTとして使わない
     * - 求人タイトルを最優先
     * - descriptionは補助情報としてのみ利用
     * - 判定できない場合はnull
     */
    public function normalize(
        ?string $title,
        ?string $description = null
    ): ?string {
        $title = $this->normalizeText($title);
        $description = $this->normalizeText($description);

        /*
        |--------------------------------------------------------------------------
        | 1. タイトルから判定
        |--------------------------------------------------------------------------
        |
        | タイトルは求人の職種を最も直接的に表しているため最優先。
        |
        */

        if ($title !== '') {
            $result = $this->classifyTitle($title);

            if ($result !== null) {
                return $result;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | 2. descriptionから補助判定
        |--------------------------------------------------------------------------
        |
        | 本文には他職種の単語も混ざりやすいため、
        | タイトルより厳しいキーワードで判定する。
        |
        */

        if ($description !== '') {
            $result = $this->classifyDescription(
                $description
            );

            if ($result !== null) {
                return $result;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | 3. 判定不能
        |--------------------------------------------------------------------------
        |
        | 推測で職種FACTを作らない。
        |
        */

        return null;
    }


    /**
     * 求人タイトルから職種分類
     */
    private function classifyTitle(
        string $title
    ): ?string {
        /*
        |--------------------------------------------------------------------------
        | ソフトウェア・IT
        |--------------------------------------------------------------------------
        |
        | 「機械学習」のような単語を
        | 機械設計と誤判定しないため先に判定。
        |
        */

        if ($this->containsAny(
            $title,
            [
                'aiエンジニア',
                'ai・データ',
                'ai/データ',
                'データサイエンティスト',
                'データサイエンス',
                '機械学習',
                '深層学習',
                '社内se',
                '社内システムエンジニア',
                'システムエンジニア',
                'ソフトウェアエンジニア',
                'ソフトウェア開発',
                'アプリケーションエンジニア',
                'webエンジニア',
                'web開発',
                'プログラマー',
                'プログラミング',
                '組み込みソフト',
                '組込ソフト',
                '制御ソフト',
                'itエンジニア',
            ]
        )) {
            return 'ソフトウェア・IT';
        }

        /*
        |--------------------------------------------------------------------------
        | 機械設計
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '機械設計',
                '機構設計',
                '筐体設計',
                '構造設計',
                '装置設計',
                '設備設計',
                '機器設計',
                '製品設計',
                '機械エンジニア',
                'メカ設計',
                'メカニカル設計',
                'メカエンジニア',
                'プラント機械設備設計',
                'プラント機械設計',
                '配管設計',
                '回転機設計',
                'タービン設計',
                '圧力容器設計',
                '熱交換器設計',
            ]
        )) {
            return '機械設計';
        }

        /*
        |--------------------------------------------------------------------------
        | 電気設計
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '電気設計',
                '電装設計',
                '回路設計',
                '電子回路設計',
                'アナログ回路',
                'デジタル回路',
                '基板設計',
                '電気エンジニア',
                '電子設計',
                '制御盤設計',
                'ハードウェア設計',
            ]
        )) {
            return '電気設計';
        }

        /*
        |--------------------------------------------------------------------------
        | 生産技術
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '生産技術',
                '製造技術',
                '工程設計',
                '生産工程',
                '工程改善',
                '設備導入',
                '生産設備',
                '製造工程',
            ]
        )) {
            return '生産技術';
        }

        /*
        |--------------------------------------------------------------------------
        | 品質保証
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '品質保証',
                '品質管理',
                '品質技術',
                'qaエンジニア',
                'qc',
            ]
        )) {
            return '品質保証';
        }

        /*
        |--------------------------------------------------------------------------
        | 施工管理
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '施工管理',
                '工事管理',
                '現場監督',
                '建設管理',
            ]
        )) {
            return '施工管理';
        }

        /*
        |--------------------------------------------------------------------------
        | プラントエンジニア
        |--------------------------------------------------------------------------
        |
        | 「プラント機械設備設計」は上で機械設計に分類済み。
        |
        */

        if ($this->containsAny(
            $title,
            [
                'プラントエンジニア',
                'プラントエンジニアリング',
                'プロセス設計',
                'プロセスエンジニア',
                'プラント計画',
            ]
        )) {
            return 'プラントエンジニア';
        }

        /*
        |--------------------------------------------------------------------------
        | その他技術職
        |--------------------------------------------------------------------------
        */

        if ($this->containsAny(
            $title,
            [
                '研究開発',
                '技術開発',
                '開発エンジニア',
                '解析エンジニア',
                'cae',
                'シミュレーション',
                '評価エンジニア',
                '試験評価',
                '技術職',
            ]
        )) {
            return 'その他技術職';
        }

        return null;
    }


