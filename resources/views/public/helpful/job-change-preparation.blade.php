    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">1. 希望職種を、仕事の内容と合わせて考える</h2>
        <p class="mt-3">「機械設計」「電気設計」という職種名だけでなく、設備や製品の何に関わりたいかを考えます。今の専門性を深めたいのか、隣接する領域へ広げたいのかによって、確認する求人の範囲も変わります。</p>
        <p class="mt-3">経験のある仕事と、これから担当してみたい仕事を分けて書き出すと、興味と経験を混同せずに整理できます。職種名を一つに絞れない段階でも構いません。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">2. 勤務地は、通勤や生活への影響まで見る</h2>
        <p class="mt-3">希望する府県や市だけでなく、通勤時間、交通手段、転勤、出張の頻度などを考えてみましょう。工場、設計拠点、客先など、働く場所によって一日の過ごし方が変わる場合があります。</p>
        <p class="mt-3">「片道の通勤時間はこの程度まで」「転居は現時点では難しい」など、自分の生活に結びついた条件にすると比較しやすくなります。住所だけでは分からない点は、確認事項として残します。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">3. 希望年収は、必要額と内訳を整理する</h2>
        <p class="mt-3">希望額に加えて、生活上必要な水準や、現職の給与の内訳を整理します。求人に書かれた年収の幅だけでなく、基本給、賞与、手当、固定残業代の有無など、比較の前提も確認しましょう。</p>
        <p class="mt-3">提示額に含まれるものが分からないときは、数字を同じ条件として扱わず、未確認とします。年収以外の条件と合わせて考えるためにも、希望と必要な水準を分けておくと役立ちます。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">4. 担当したい工程を言葉にする</h2>
        <p class="mt-3">構想から関わりたい、詳細設計に集中したい、評価や現場改善まで見たいなど、希望する工程を書き出します。今の担当工程で得意なことと、次に経験したいことは分けて考えてみてください。</p>
        <p class="mt-3">求人の「設計業務全般」という表現だけでは、配属直後に担当する工程まで分からないことがあります。最初の担当業務と、その後に関われる工程をそれぞれ確認すると比較の材料になります。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">5. 働き方と、譲れない条件を整理する</h2>
        <p class="mt-3">残業、休日、勤務時間、チームでの進め方など、長く働くうえで気になることを挙げます。家族との時間や体調管理など、自分の事情に照らして考え、周囲の希望に合わせすぎないようにしましょう。</p>
        <p class="mt-3">条件は「譲れない条件」と「できれば満たしたい条件」に分けても構いません。例えば、通勤時間は優先したいが、担当工程には幅を持たせられる、といった整理です。</p>
    </section>
    <section class="jobdd-decision-note">
        <h2 class="text-xl font-bold leading-8 text-blue-950">自分の場合を整理して、比べる</h2>
        <p class="mt-3">5項目を書いたら、優先順位と、その理由を一言ずつ添えてみてください。すべてを満たす求人を探すだけでなく、何が満たされ、何が未確認で、どこに調整の余地があるかを見ることができます。こういう観点で求人を比較し、現職も含めて自分に合う選択を考えてみてください。</p>
    </section>
