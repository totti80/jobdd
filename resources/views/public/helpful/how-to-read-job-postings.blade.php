    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">1. 何を設計する仕事か</h2>
        <p class="mt-3">製品、設備、装置、部品など、設計対象を確認します。「生産設備の設計」でも、設備全体の配置を考える仕事と、一部の機構や部品を担当する仕事では関わる範囲が異なります。</p>
        <p class="mt-3">用途や対象の規模、既存設備の改良か新規設計かも、仕事を理解する材料です。記載がない場合は、「入社後はどのような設備の、どの部分を担当しますか」と具体的に聞いてみましょう。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">2. どの工程を担当するか</h2>
        <p class="mt-3">構想、基本設計、詳細設計、製作図作成、評価、現場対応のうち、どこが中心になるかを見ます。「一貫して担当」という表現があっても、すべてを一人で行うのか、チームで分担するのかは別の確認事項です。</p>
        <p class="mt-3">入社直後の担当業務と、経験を積んだ後に関われる工程を分けて確かめると、自分が担当したい工程と照らし合わせやすくなります。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">3. CADやToolを何に使うか</h2>
        <p class="mt-3">ソフト名に加えて、図面作成、モデリング、解析、資料作成など、使う場面を確認します。複数のツールが並んでいる場合は、主に使うものと、補助的に使うものを分けて理解しましょう。</p>
        <p class="mt-3">業務で使用するツールと、応募時に経験が求められるツールは同じとは限りません。「入社後に学べる範囲はどこか」も確認し、使用実態と経験要件を混同しないようにします。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">4. 誰と、どのように仕事を進めるか</h2>
        <p class="mt-3">設計チーム、製造、品質、顧客、現場担当など、主な関係者を確認します。打ち合わせの相手だけでなく、仕様を決める人、図面をレビューする人、困ったときに相談できる人を知ることも役立ちます。</p>
        <p class="mt-3">「コミュニケーション力が必要」という言葉だけでは、調整の内容は分かりません。「製造担当との相談はどの工程で、どのくらいありますか」といった質問に置き換えてみましょう。</p>
    </section>
    <section>
        <h2 class="text-xl font-bold leading-8 text-blue-950">5. 難しい点と、普段の一日を聞く</h2>
        <p class="mt-3">設計精度、納期調整、不具合対応など、仕事で難しい点を聞くと、求められる役割が見えやすくなります。同時に、相談やレビュー、教育など、課題に向き合うための支援も確認してください。</p>
        <p class="mt-3">Typical Day、つまり普段の一日の例も比較材料になります。図面作成と打ち合わせの割合、現場へ行く時間、繁忙期との違いなどを聞くと、抽象的な業務説明を具体的な働き方へ近づけられます。</p>
    </section>
    <section class="jobdd-decision-note">
        <h2 class="text-xl font-bold leading-8 text-blue-950">自分の場合を整理して、比べる</h2>
        <p class="mt-3">求人ごとに「設計対象・工程・Tool・関係者・一日の流れ」を並べ、出典と未確認の点をメモしてみてください。分からない点は面談の質問にできます。職種名や給与に加え、こういう観点で仕事の中身を比較し、自分の経験や希望との関係を考えてみてください。</p>
    </section>
